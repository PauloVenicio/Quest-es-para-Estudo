function saoMateusExpandirConceitos(chave) {
 const itens=saoMateusConceitos[chave]||[];
 if(itens.length<4)return [];
 const saida=[];
 itens.forEach(([nome,def],i)=>{
   const outros=[1,3,5].map(v=>itens[(i+v)%itens.length]);
   saida.push({
     question:"Em relação a "+chave.replaceAll("_"," ")+", qual termo corresponde a: "+def+"?",
     options:[nome,...outros.map(x=>x[0])],correct:0,
     explanation:nome+": "+def+".",topic:nome,subject:chave
   });
   saida.push({
     question:"No conteúdo de "+chave.replaceAll("_"," ")+", a expressão \""+nome+"\" corresponde a:",
     options:[def,...outros.map(x=>x[1])],correct:0,
     explanation:nome+": "+def+".",topic:nome,subject:chave
   });
 });
 return saida;
}
